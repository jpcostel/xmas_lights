def scroll_text(strips, message, text_color, bg_color, speed=0.05):
    # Build column bitmap for entire message
    columns = []
    for ch in message:
        if ch not in FONT:
            ch = " "
        columns.extend(FONT[ch])
        columns.append(0x00)  # spacing

    text_width = len(columns)

    for offset in range(text_width + COLS):
        # Background fill
        for row in range(ROWS):
            for col in range(COLS):
                strand, idx = grid_to_pixel(row, col)
                strips[strand][idx] = bg_color

        # Draw text
        for x in range(text_width):
            screen_col = COLS - 1 - offset + x
            if 0 <= screen_col < COLS:
                bits = columns[x]
                for y in range(7, -1, -1):
                    if bits & (1 << y):
                        row = y + 1  # center text vertically
                        strand, idx = grid_to_pixel(row, screen_col)
                        strips[strand][idx] = text_color

        for s in strips:
            s.write()

        time.sleep(speed)
